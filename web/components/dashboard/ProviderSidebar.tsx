const PRIMARY_ITEMS = [
  { href: '/provider', label: 'Home', icon: ICONS.home },
  { href: '/provider/bookings', label: 'Appointments', icon: ICONS.appointments },
  { href: '/provider/services', label: 'Services', icon: ICONS.services },
  { href: '/provider/specialists', label: 'Specialists', icon: ICONS.specialists },
  { href: '/provider/customers', label: 'Customers', icon: ICONS.customers },
];

const PROFILE_SUB_ITEMS = [
  { href: '/provider/business-profile', label: 'Account Information', icon: ICONS.accountInfo },
  { href: '/provider/payments', label: 'Payments', icon: ICONS.payments },
  { href: '/provider/reviews', label: 'Reviews & Ratings', icon: ICONS.reviews },
  { href: '/provider/calendar', label: 'Calendar & Availability', icon: ICONS.calendar },
  { href: '/provider/settings', label: 'Settings', icon: ICONS.settings },
];

export function ProviderSidebar() {
  const pathname = usePathname();
  const isActive = (href: string) => (href === '/provider' ? pathname === '/provider' : pathname.startsWith(href));
  const profileSectionActive = PROFILE_SUB_ITEMS.some((item) => pathname.startsWith(item.href));
  const [profileOpen, setProfileOpen] = useState(profileSectionActive);

  return (
   <aside className="fixed inset-y-0 left-0 hidden w-64 flex-col overflow-y-auto border-r border-bloom-800 bg-bloom-700 pt-[57px] md:flex">
      <nav className="flex flex-1 flex-col gap-1 px-3 py-4">
        {PRIMARY_ITEMS.map((item) => {
          const active = isActive(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
               active
  ? 'bg-white text-bloom-700 shadow-sm'
  : 'text-white hover:bg-bloom-600'
              }`}
            >
              <Icon path={item.icon} />
              {item.label}
            </Link>
          );
        })}

       <div className="my-2 border-t border-white/20" />

        <button
          onClick={() => setProfileOpen((v) => !v)}
          className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
           profileSectionActive
  ? 'bg-white text-bloom-700 shadow-sm'
  : 'text-white hover:bg-bloom-600'
          }`}
        >
          <Icon path={ICONS.profile} />
          <span className="flex-1 text-left">Profile</span>
          <Icon path={ICONS.chevron} className={`h-4 w-4 transition-transform ${profileOpen ? 'rotate-90' : ''}`} />
        </button>

        {profileOpen && (
         <div className="ml-4 flex flex-col gap-1 border-l border-white/20 pl-3">
            {PROFILE_SUB_ITEMS.map((item) => {
              const active = pathname.startsWith(item.href);
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  className={`flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
                   active
  ? 'bg-white text-bloom-700 shadow-sm'
  : 'text-white/80 hover:bg-bloom-600 hover:text-white'
                  }`}
                >
                  <Icon path={item.icon} className="h-4 w-4" />
                  {item.label}
                </Link>
              );
            })}
          </div>
        )}
      </nav>
    </aside>
  );
}